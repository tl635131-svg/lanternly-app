const DICTS: Record<string, InviteDict> = { en, fr };
export const inviteDict = (lang?: string | null): InviteDict => DICTS[(lang ?? "en").slice(0, 2).toLowerCase()] ?? en;

const Ctx = createContext<InviteDict>(en);
export function InviteLangProvider({ lang, children }: { lang?: string | null; children: ReactNode }) {
  return <Ctx.Provider value={inviteDict(lang)}>{children}</Ctx.Provider>;
}
export const useIt = () => useContext(Ctx);
